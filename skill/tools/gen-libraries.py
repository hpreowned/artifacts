#!/usr/bin/env python3
"""Render references/python-1-libraries.md from the runtime manifest. Standard library only.

Usage: gen-libraries.py <runtime-manifest.json> [<output.md>]
Without an output path the markdown goes to stdout. The platform's CI runs this against the
runtime-manifest.json it publishes next to the python-runtime image; the repo copy is generated from
tests/runtime-manifest.python-1.json so the skill and the scanner agree on one list.
"""
import json
import sys


def render(manifest: dict) -> str:
    runtime = manifest["runtime"]
    modules = sorted(manifest["modules"])
    entrypoints = manifest["entrypoints"]
    lines = [
        f"# Libraries available in runtime `{runtime}`",
        "",
        "Generated by `skill/tools/gen-libraries.py` from the runtime manifest. Do not edit by hand.",
        "",
        f"- Image: `{manifest['image']}`",
        f"- Python: {manifest['python']}",
        "",
        "## Importable third-party modules",
        "",
        "Anything not in this list and not in the Python standard library is rejected (rule PY-001).",
        "`requirements.txt` is rejected (rule PY-004): dependencies are fixed by the runtime.",
        "",
    ]
    lines += [f"- `{m}`" for m in modules]
    lines += [
        "",
        "## Entrypoint styles",
        "",
        "The bundle is a single `app.py`. Intake picks the launcher from the import it finds:",
        "",
    ]
    for name, argv in entrypoints.items():
        lines.append(f"### {name}")
        lines.append("")
        lines.append("```")
        lines.append(" ".join(argv))
        lines.append("```")
        lines.append("")
    lines += [
        "- `streamlit`: write a plain Streamlit script; it is run with `streamlit run`.",
        "- `fastapi`: expose `app = FastAPI()` at module level; it is served by uvicorn on port 8080.",
        "",
        "## Not available",
        "",
        "- No outbound network: `socket`, `requests`, `httpx`, `urllib.request` to anything will fail or be rejected.",
        "- No `subprocess`, `os.system`, `ctypes`, `pickle`, `marshal`, `eval`, `exec`, `__import__`, `importlib` (rule PY-002).",
        "- File writes only under `/tmp` (rule PY-003).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) < 2 or len(argv) > 3:
        print(__doc__, file=sys.stderr)
        return 1
    with open(argv[1], encoding="utf-8") as f:
        manifest = json.load(f)
    text = render(manifest)
    if len(argv) == 3:
        with open(argv[2], "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
